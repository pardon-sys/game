    line(53, 14, 90, 14, 2)          # 猫咪追逐：两格宽
    line(90, 14, 90, 23, 2)
    line(90, 22, 61, 22, 2)
    line(60, 22, 60, 31)             # 小洞往南
    line(60, 28, 66, 28)
    room(66, 26, 72, 30)             # 老鼠的小洞穴
    line(60, 31, 28, 31)             # 竖井前的通道
    room(26, 29, 29, 31)             # 竖井底
    line(72, 28, 76, 28)             # 老鼠的小洞穴往东：胖鼠王的洞底
