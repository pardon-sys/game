def grid(fid):
    rows = LAYOUTS[fid]
    w = max(len(r) for r in rows)
    return [list(r.ljust(w, "#")) for r in rows]


def _walk_dist(g, start):
    """从 start 走过去的步数（道具当墙；走不到的不在里面）"""
    h, w = len(g), len(g[0])
    dist = {start: 0}
    dq = deque([start])
    while dq:
        x, y = dq.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < w and 0 <= ny < h and (nx, ny) not in dist and (g[ny][nx] == "." or g[ny][nx].isupper()):
                dist[(nx, ny)] = dist[(x, y)] + 1
                dq.append((nx, ny))
    return dist


def marks(fid):
    """{名字: [[x, y], …]}（按从 P 走过去的远近排：封印钉、房檐手印这些要按路上的顺序）"""
    g = grid(fid)
    names = dict(COMMON, **MARKS[fid])
    out = {}
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch in names:
                out.setdefault(names[ch], []).append([x, y])
    dist = _walk_dist(g, tuple(out["start"][0]))
    for cells in out.values():
        cells.sort(key=lambda c: (dist.get(tuple(c), 1 << 20), c[1], c[0]))
    return out


def check(fid):
    g = grid(fid)
    h, w = len(g), len(g[0])
    for y in range(h):
        for x in range(w):
            ch = g[y][x]
            if ch != "#" and (x in (0, w - 1) or y in (0, h - 1)) and ch not in "X":
                raise SystemExit("%s：(%d, %d) 的 %r 在地图边上" % (fid, x, y, ch))
            if ch not in "#." and not ch.isupper() and ch not in PROPS:
                raise SystemExit("%s：(%d, %d) 不认识的字符 %r" % (fid, x, y, ch))
    m = marks(fid)
    seen = _walk_dist(g, tuple(m["start"][0]))
    for name, cells in m.items():
        for x, y in cells:
            if (x, y) not in seen:
                raise SystemExit("%s：标记 %s (%d, %d) 走不到" % (fid, name, x, y))
    return m


def build(Map, fid, header, prop, torch=None, torch_every=9):
    """按布局画好 Map（墙、地面、道具；torch = "torch lit=true" 之类时，每隔 torch_every 列在地面上方的墙上挂一个）；
    返回 (Map, 标记点)。出口 / 出生点 / 玩家由调用方按标记点摆。"""
    g = grid(fid)
    m = Map(fid, len(g[0]), len(g), header)
    last = -torch_every
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch == "#":
                continue
            m.g[y][x] = "."
            if ch in PROPS:
                prop(m, x, y, PROPS[ch])
    if torch:
        for x in range(len(g[0])):
            for y in range(1, len(g) - 1):
                if g[y][x] == "#" and g[y + 1][x] != "#" and x - last >= torch_every and (y == 0 or g[y - 1][x] == "#"):
                    m.put(x, y, torch)
                    last = x
                    break
    return m, check(fid)
