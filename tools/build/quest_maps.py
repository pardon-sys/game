def _disk(g, cx, cy, r, ch="."):
    """画一个圆（圆形的凸室 / 半圆的凹位）；不出画布边界、留一圈外墙"""
    for y in range(max(1, cy - r), min(len(g) - 1, cy + r + 1)):
        for x in range(max(1, cx - r), min(len(g[0]) - 1, cx + r + 1)):
            if (x - cx) ** 2 + (y - cy) ** 2 <= r * r + r:
                g[y][x] = ch


