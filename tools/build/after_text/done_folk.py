def apply(cid, data):
    """把民风段落接在过场最后一句台词后面（镜头复位 / 回地图之前）。"""
    extra = FOLK.get(cid)
    if not extra:
        return data
    steps = data["steps"]
    last = max(i for i, st in enumerate(steps) if st.get("text"))
    steps[last + 1:last + 1] = [dict(x) for x in extra]
    return data
