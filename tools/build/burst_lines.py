## 立绘：战损魔力释放（以后放了正式素材 assets/cg/portraits/fatigue_burst.png 就自动换上）
PORTRAIT = "fatigue_burst"
PORTRAIT_INFO = {"file": "res://assets/cg/portraits/fatigue_burst.png", "placeholder": "damaged_burst"}
P = "公主"


def burst_steps(lines, name, movers, fx="lines"):
    """lines：上面的 7 句；name：怪物台词的说话人；movers：[(演员名, [x, y])] 被爆发震开、之后又回来的怪物演员。
    所有步骤都标了 "act": "burst"（测试和演出统计用）。"""
    def speaker(w):
        return {"P": P, "M": name, "N": ""}[w]

    def tickles(repeat, interval):
        if not movers:
            return [{"do": "tickle", "who": "princess", "repeat": repeat, "interval": interval, "fx": fx}]
        return [{"do": "tickle", "who": "princess", "by": who, "repeat": repeat, "interval": interval, "fx": fx} for who, _ in movers]

    def line(i, actions):
        w, t = lines[i]
        return {"act": "burst", "speaker": speaker(w), "text": t, "actions": actions}

    steps = [
        # 魔力疲倦满了
        line(0, [{"do": "shake", "who": "princess", "time": 0.8}, {"do": "bubble", "who": "princess", "kind": "surprise"},
                 {"do": "voice", "state": "laugh"}] + tickles(6, 0.24)),
        # 要溢出来了
        line(1, [{"do": "shake", "who": "princess", "time": 1.2}, {"do": "camera", "zoom": 1.5, "focus": "princess", "time": 0.4},
                 {"do": "flash", "time": 0.2}]),
    ]
    # 爆发：白光、星光爆发 + 释放的水声，怪物被震开；立绘换成战损魔力释放
    boom = [{"do": "flash", "time": 0.8}, {"do": "sfx", "sound": "star_burst", "volume": -1.0},
            {"do": "sfx", "sound": "water_release", "volume": -2.0}, {"do": "voice", "state": ""},
            {"do": "shake", "who": "princess", "time": 0.5}, {"do": "camera", "zoom": 1, "focus": "princess", "time": 0.5}]
    for who, at in movers:
        boom.append({"do": "move", "who": who, "to": [at[0] + (60 if at[0] >= 0 else -60), at[1] - 6], "time": 0.25})
    steps.append({"act": "burst", "portrait": PORTRAIT, "actions": boom, "wait": 1.1})
    # 畅快
    steps.append(line(2, [{"do": "bubble", "who": "princess", "kind": "shy"}]))
    # 它们又回来了
    back = [{"do": "move", "who": who, "to": list(at), "time": 0.6} for who, at in movers]
    steps.append(line(3, back + [{"do": "voice", "state": "giggle"}] + tickles(4, 0.3)))
    # 更敏感、更痒
    steps.append(line(4, [{"do": "voice", "state": "laugh"}, {"do": "shake", "who": "princess", "time": 0.8},
                          {"do": "bubble", "who": "princess", "kind": "laugh"}] + tickles(10, 0.16)))
    steps.append(line(5, [{"do": "shake", "who": "princess", "time": 0.6}] + tickles(10, 0.15)))
    steps.append(line(6, [{"do": "bubble", "who": "princess", "kind": "dots"}] + tickles(6, 0.22)))
    return steps
