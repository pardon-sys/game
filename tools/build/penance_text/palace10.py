def _small(kind):
    who, faded, colour, talks = SMALL[kind]
    n = len(talks)
    nodes = {
        "default": {"lines": [L("（褪了色的小画像，灰扑扑的。它轻轻地叹了一口气）", N), L(faded, who)]},
        "paint": {"lines": [L(colour, N)], "set": {"call": "palace_small_color_" + kind, "flags": ["palace_small_" + kind]}, "next": "talk"},
        "talk": {"set": {"vars": {"pick_key": "small_" + kind, "pick_n": n}, "call": "pick_unheard"}, "next": "say"},
        "say": {"goto": [{"if": {"eq": {"pick": i}}, "node": "t%d" % i} for i in range(n)]},
    }
    for i, t in enumerate(talks):
        nodes["t%d" % i] = {"lines": [L(x, who) for x in t]}
    return dfile("", who, nodes, entries=[{"if": {"flag": "palace_small_" + kind}, "node": "talk"},
                                          {"if": {"flag": "palace_paint_" + kind}, "node": "paint"}, {"node": "default"}])


