def _read(name, lines, flag, extra=None, entries_done=None):
    nodes = {"default": {"lines": lines, "set": {"flags": [flag]}},
             "done": {"lines": entries_done or lines}}
    if extra:
        nodes["default"]["next"] = "more"
        nodes["more"] = extra
        nodes["done"]["next"] = "more"
    return dfile("", name, nodes, entries=[{"if": {"flag": flag}, "node": "done"}, {"node": "default"}])


